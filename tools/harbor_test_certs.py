"""Test certificates for the Harbor's CA binding: two partner ring CAs and three client leaves,
written as a Rego test file so `opa test` needs nothing else. Fictitious rings only (s.vdh.test, x.vdh.test).

- ca_s, ca_x: the CAs of partner rings S and X (self-signed, EC P-256);
- leaf_s: S's Harbor client certificate (URI SAN spiffe://s.vdh.test/harbor), signed by ca_s;
- leaf_forged: the same URI SAN, signed by ca_x (what partner X's CA could mint to be decided as S);
- leaf_expired: S's client certificate, signed by ca_s, no longer valid.
Each leaf is also given as Envoy writes it into x-forwarded-client-cert (Cert="..."): percent-encoded, every byte
but the RFC 3986 unreserved characters.

Usage: python tools/harbor_test_certs.py   (rewrites gitops/lab/harbor/harbor_test_certs.rego)
"""
from __future__ import annotations

import datetime as dt
from pathlib import Path
from urllib.parse import quote

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import NameOID

OUT = Path(__file__).resolve().parent.parent / "gitops" / "lab" / "harbor" / "harbor_test_certs.rego"
S = "spiffe://s.vdh.test/harbor"
START = dt.datetime(2026, 1, 1, tzinfo=dt.timezone.utc)
END = dt.datetime(2199, 12, 31, tzinfo=dt.timezone.utc)


def _name(cn: str) -> x509.Name:
    return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])


def ca(cn: str):
    key = ec.generate_private_key(ec.SECP256R1())
    cert = (x509.CertificateBuilder().subject_name(_name(cn)).issuer_name(_name(cn)).public_key(key.public_key())
            .serial_number(x509.random_serial_number()).not_valid_before(START).not_valid_after(END)
            .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
            .add_extension(x509.KeyUsage(False, False, False, False, False, True, True, False, False), critical=True)
            .sign(key, hashes.SHA256()))
    return key, cert


def leaf(issuer_key, issuer, uri: str, start=START, end=END):
    key = ec.generate_private_key(ec.SECP256R1())
    return (x509.CertificateBuilder().subject_name(_name("harbor client")).issuer_name(issuer.subject)
            .public_key(key.public_key()).serial_number(x509.random_serial_number())
            .not_valid_before(start).not_valid_after(end)
            .add_extension(x509.SubjectAlternativeName([x509.UniformResourceIdentifier(uri)]), critical=False)
            .add_extension(x509.ExtendedKeyUsage([x509.oid.ExtendedKeyUsageOID.CLIENT_AUTH]), critical=False)
            .sign(issuer_key, hashes.SHA256()))


def pem(c) -> str:
    return c.public_bytes(serialization.Encoding.PEM).decode("ascii")


def main() -> None:
    ks, cs = ca("vdh ring s CA")
    kx, cx = ca("vdh ring x CA")
    leaves = {"leaf_s": leaf(ks, cs, S), "leaf_forged": leaf(kx, cx, S),
              "leaf_expired": leaf(ks, cs, S, dt.datetime(2020, 1, 1, tzinfo=dt.timezone.utc),
                                   dt.datetime(2021, 1, 1, tzinfo=dt.timezone.utc))}
    lines = ["# Generated by tools/harbor_test_certs.py: test certificates only, fictitious rings. Do not edit.",
             "package vdh.harbor_test", "", "import rego.v1", "",
             f"ca_s := {pem(cs)!r}".replace("'", '"'), "", f"ca_x := {pem(cx)!r}".replace("'", '"'), ""]
    for name, c in leaves.items():
        lines += [f"{name} := {pem(c)!r}".replace("'", '"'), "",
                  f'{name}_xfcc := "{quote(pem(c), safe="")}"', ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"written {OUT}")


if __name__ == "__main__":
    main()
